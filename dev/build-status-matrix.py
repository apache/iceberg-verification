import json
import os
import re
import sys

TOTALS_RE = re.compile(
    r"TOTALS:\s*(\d+)\s*cases\s*\|\s*PASS=(\d+)\s*FAIL=(\d+)\s*UNSUPPORTED=(\d+)\s*SKIP=(\d+)"
)

