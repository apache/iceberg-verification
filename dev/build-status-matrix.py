"""Aggregate runner outputs into a cross-implementation STATUS.md matrix.

Reads a directory of runner-output files named <implementation>.txt (each the
captured stdout of a conformance runner) and writes a Markdown status matrix.
It reports counts and divergences; it does not block.

Usage:
  dev/build-status-matrix.py <outputs-dir> [<status.md>]     render the matrix
  dev/build-status-matrix.py --json <outputs-dir> <json-dir> per-impl badge JSON
"""

